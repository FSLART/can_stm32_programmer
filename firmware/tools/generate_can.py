"""Regenerate the firmware CAN codec after saving docs/bootloader.dbc."""
from pathlib import Path
import re

import cantools
from cantools.database.can import c_source

ROOT = Path(__file__).resolve().parents[1]


def generate():
    database = cantools.database.load_file(ROOT / "docs/bootloader.dbc", strict=True)
    header, source, _, _ = c_source.generate(
        database, "bootloader", "bootloader.h", "bootloader.c", "bootloader_fuzzer.c")
    # Keep regeneration reproducible; cantools otherwise inserts the current time.
    return [re.sub(r"(\* @brief This (?:header|source) file was generated by cantools version [^\s]+) .*", r"\1.", text)
            for text in (header, source)]


if __name__ == "__main__":
    for path, text in zip((ROOT / "Core/Inc/bootloader.h", ROOT / "Core/Src/bootloader.c"), generate()):
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"Generated {path.relative_to(ROOT)}")
